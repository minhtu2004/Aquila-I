#!/usr/bin/env python3
# =============================================================================
# hex2rom.py — Convert firmware.hex → rom.v (firmware bake-in)
# -----------------------------------------------------------------------------
# Usage:
#   python3 hex2rom.py firmware.hex rom.v
#   python3 hex2rom.py firmware.hex          → ghi ra rom.v mặc định
#   python3 hex2rom.py --help
# -----------------------------------------------------------------------------
# Input : firmware.hex (định dạng Intel HEX hoặc plain hex từ objcopy)
# Output: rom.v với firmware bake-in vào case statement
# =============================================================================

import sys
import os

# -----------------------------------------------------------------------------
# Config
# -----------------------------------------------------------------------------
ROM_SIZE_BYTES  = 8 * 1024          # 8KB
ROM_DEPTH_WORDS = ROM_SIZE_BYTES // 4  # 2048 words
ADDR_BITS       = 11                # ceil(log2(2048))

# -----------------------------------------------------------------------------
# Parse Intel HEX format
# -----------------------------------------------------------------------------
def parse_intel_hex(lines):
    data = {}
    base_addr = 0

    for lineno, line in enumerate(lines, 1):
        line = line.strip()
        if not line or not line.startswith(':'):
            continue

        # Strip ':'
        line = line[1:]

        try:
            byte_count  = int(line[0:2],   16)
            address     = int(line[2:6],   16)
            record_type = int(line[6:8],   16)
            payload     = line[8:8 + byte_count * 2]
            checksum    = int(line[8 + byte_count * 2 : 10 + byte_count * 2], 16)
        except ValueError:
            print(f"[ERROR] Line {lineno}: parse failed → '{line}'")
            sys.exit(1)

        # Verify checksum
        raw = [int(line[i:i+2], 16) for i in range(0, 8 + byte_count * 2, 2)]
        if (sum(raw) + checksum) & 0xFF != 0:
            print(f"[WARN]  Line {lineno}: checksum mismatch")

        if record_type == 0x00:  # Data
            abs_addr = base_addr + address
            for i in range(byte_count):
                byte_val = int(payload[i*2 : i*2+2], 16)
                data[abs_addr + i] = byte_val

        elif record_type == 0x01:  # End Of File
            break

        elif record_type == 0x02:  # Extended Segment Address
            base_addr = int(payload, 16) << 4

        elif record_type == 0x04:  # Extended Linear Address
            base_addr = int(payload, 16) << 16

        elif record_type == 0x05:  # Start Linear Address (ignore)
            pass

    return data


# -----------------------------------------------------------------------------
# Parse plain hex format (1 word per line, từ objcopy -O verilog)
# -----------------------------------------------------------------------------
def parse_plain_hex(lines):
    data = {}
    byte_addr = 0

    for line in lines:
        line = line.strip()
        if not line:
            continue

        # objcopy verilog format có thể có @address
        if line.startswith('@'):
            byte_addr = int(line[1:], 16)   # word address → byte address
            continue

        # Mỗi token là 1 byte (objcopy -O verilog xuất từng byte)
        tokens = line.split()
        for token in tokens:
            try:
                val = int(token, 16)
                data[byte_addr] = val
                byte_addr += 1
            except ValueError:
                continue

    return data


# -----------------------------------------------------------------------------
# Assemble bytes → words (little-endian)
# -----------------------------------------------------------------------------
def bytes_to_words(byte_data):
    words = {}
    max_byte = max(byte_data.keys()) if byte_data else 0
    max_word = max_byte // 4

    for word_idx in range(max_word + 1):
        base = word_idx * 4
        b0 = byte_data.get(base + 0, 0x00)
        b1 = byte_data.get(base + 1, 0x00)
        b2 = byte_data.get(base + 2, 0x00)
        b3 = byte_data.get(base + 3, 0x00)
        words[word_idx] = (b3 << 24) | (b2 << 16) | (b1 << 8) | b0

    return words


# -----------------------------------------------------------------------------
# Generate rom.v
# -----------------------------------------------------------------------------
def generate_rom_v(words, output_path):
    lines = []

    lines.append('`timescale 1ns / 1ps')
    lines.append('// ' + '=' * 77)
    lines.append('// AXI4-Lite ROM — 8KB Read Only')
    lines.append('// ' + '-' * 77)
    lines.append('// AUTO-GENERATED by hex2rom.py — DO NOT EDIT MANUALLY')
    lines.append(f'// Source : {os.path.basename(output_path).replace(".v", ".hex")}')
    lines.append(f'// Words  : {len(words)} / {ROM_DEPTH_WORDS}')
    lines.append('// ' + '=' * 77)
    lines.append('module rom (')
    lines.append('    input  wire        clk,')
    lines.append('    input  wire        resetn,')
    lines.append('')
    lines.append('    // Read Address Channel')
    lines.append('    input  wire [31:0] s_axi_araddr,')
    lines.append('    input  wire        s_axi_arvalid,')
    lines.append('    output reg         s_axi_arready,')
    lines.append('')
    lines.append('    // Read Data Channel')
    lines.append('    output reg  [31:0] s_axi_rdata,')
    lines.append('    output reg  [ 1:0] s_axi_rresp,')
    lines.append('    output reg         s_axi_rvalid,')
    lines.append('    input  wire        s_axi_rready')
    lines.append(');')
    lines.append('')
    lines.append('    // =========================================================================')
    lines.append('    // ROM Content (firmware bake-in)')
    lines.append('    // =========================================================================')
    lines.append('    function [31:0] rom_read;')
    lines.append(f'        input [{ADDR_BITS-1}:0] word_addr;')
    lines.append('        begin')
    lines.append('            case (word_addr)')

    # Case entries — chỉ emit word có data thực (khác NOP)
    NOP = 0x00000013
    for word_idx in sorted(words.keys()):
        if word_idx >= ROM_DEPTH_WORDS:
            print(f"[WARN] Word 0x{word_idx:04X} vượt quá ROM size ({ROM_DEPTH_WORDS} words), bỏ qua")
            continue
        val = words[word_idx]
        lines.append(f"                {ADDR_BITS}'h{word_idx:03X}: rom_read = 32'h{val:08X};")

    lines.append(f"                default: rom_read = 32'h{NOP:08X}; // NOP")
    lines.append('            endcase')
    lines.append('        end')
    lines.append('    endfunction')
    lines.append('')
    lines.append('    // =========================================================================')
    lines.append('    // Read Path — 1 cycle latency')
    lines.append('    // =========================================================================')
    lines.append(f'    reg [{ADDR_BITS-1}:0] ar_addr_lat;')
    lines.append('    reg        ar_pending;')
    lines.append('')
    lines.append('    always @(posedge clk) begin')
    lines.append('        if (!resetn) begin')
    lines.append(f'            ar_addr_lat   <= {ADDR_BITS}\'h0;')
    lines.append('            ar_pending    <= 1\'b0;')
    lines.append('            s_axi_arready <= 1\'b0;')
    lines.append('            s_axi_rvalid  <= 1\'b0;')
    lines.append('            s_axi_rdata   <= 32\'h0;')
    lines.append('            s_axi_rresp   <= 2\'b00;')
    lines.append('        end else begin')
    lines.append('')
    lines.append('            s_axi_arready <= 1\'b0;')
    lines.append('')
    lines.append('            if (s_axi_arvalid && !ar_pending && !s_axi_rvalid) begin')
    lines.append('                ar_addr_lat   <= s_axi_araddr[12:2];')
    lines.append('                ar_pending    <= 1\'b1;')
    lines.append('                s_axi_arready <= 1\'b1;')
    lines.append('            end')
    lines.append('')
    lines.append('            if (ar_pending) begin')
    lines.append('                s_axi_rdata  <= rom_read(ar_addr_lat);')
    lines.append('                s_axi_rresp  <= 2\'b00;')
    lines.append('                s_axi_rvalid <= 1\'b1;')
    lines.append('                ar_pending   <= 1\'b0;')
    lines.append('            end')
    lines.append('')
    lines.append('            if (s_axi_rvalid && s_axi_rready) begin')
    lines.append('                s_axi_rvalid <= 1\'b0;')
    lines.append('            end')
    lines.append('')
    lines.append('        end')
    lines.append('    end')
    lines.append('')
    lines.append('endmodule')

    with open(output_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')

    print(f"[OK] Generated: {output_path}")
    print(f"     Words used : {len(words)} / {ROM_DEPTH_WORDS} ({len(words)*100//ROM_DEPTH_WORDS}%)")


# -----------------------------------------------------------------------------
# Main
# -----------------------------------------------------------------------------
def main():
    if len(sys.argv) < 2 or '--help' in sys.argv:
        print("Usage: python3 hex2rom.py <firmware.hex> [rom.v]")
        print("")
        print("  firmware.hex : Intel HEX hoặc plain hex (objcopy -O verilog)")
        print("  rom.v        : output file (default: rom.v)")
        sys.exit(0)

    hex_path = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) >= 3 else 'rom.v'

    if not os.path.exists(hex_path):
        print(f"[ERROR] File không tồn tại: {hex_path}")
        sys.exit(1)

    with open(hex_path, 'r') as f:
        lines = f.readlines()

    # Auto-detect format
    is_intel_hex = any(l.strip().startswith(':') for l in lines)

    print(f"[INFO] Format: {'Intel HEX' if is_intel_hex else 'Plain HEX (objcopy)'}")

    if is_intel_hex:
        byte_data = parse_intel_hex(lines)
    else:
        byte_data = parse_plain_hex(lines)

    if not byte_data:
        print("[ERROR] Không đọc được data từ file hex")
        sys.exit(1)

    words = bytes_to_words(byte_data)
    generate_rom_v(words, out_path)


if __name__ == '__main__':
    main()
